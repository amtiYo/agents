/**
 * Render Goose extensions.
 *
 * Goose stores secrets as `env_keys` (names resolved from the environment), never as values,
 * so env values are dropped here and only their keys are passed through.
 */
export function renderGooseExtensions(servers: ResolvedMcpServer[]): {
  extensions: Record<string, unknown>
  warnings: string[]
} {
  const warnings: string[] = []
  const out: Record<string, unknown> = {}

  for (const server of servers) {
    const timeout = typeof server.timeout === 'number' ? Math.max(1, Math.round(server.timeout / 1000)) : undefined

    if (server.transport === 'stdio') {
      if (!server.command) {
        warnings.push(`Server "${server.name}" has no command; skipped in Goose output.`)
        continue
      }
      const envKeys = Object.keys(server.env ?? {}).sort()
      if (envKeys.length > 0) {
        warnings.push(
          `Server "${server.name}": Goose reads secrets from the environment, so ${envKeys.join(', ')} are passed as env_keys and must exist in your shell.`,
        )
      }
      out[server.name] = {
        name: server.name,
        type: 'stdio',
        enabled: true,
        cmd: server.command,
        args: server.args ?? [],
        ...(envKeys.length > 0 ? { env_keys: envKeys } : {}),
        ...(timeout ? { timeout } : {})
      }
      continue
    }

    if (!server.url) {
      warnings.push(`Server "${server.name}" has no url; skipped in Goose output.`)
      continue
    }
    out[server.name] = {
      name: server.name,
      type: server.transport === 'sse' ? 'sse' : 'streamable_http',
      enabled: true,
      uri: server.url,
      ...(server.headers ? { headers: server.headers } : {}),
      ...(timeout ? { timeout } : {})
    }
  }

  return { extensions: out, warnings }
}
