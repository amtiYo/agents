/** Render Factory Droid's `.factory/mcp.json`. */
export function renderDroidMcp(servers: ResolvedMcpServer[]): {
  mcpServers: Record<string, unknown>
  warnings: string[]
} {
  const warnings: string[] = []
  const out: Record<string, unknown> = {}

  for (const server of servers) {
    const shared = {
      ...(typeof server.timeout === 'number' ? { timeout: server.timeout } : {}),
      ...(typeof server.connectTimeout === 'number' ? { connectTimeout: server.connectTimeout } : {}),
      ...(server.disabledTools ? { disabledTools: server.disabledTools } : {})
    }

    if (server.transport === 'stdio') {
      if (!server.command) {
        warnings.push(`Server "${server.name}" has no command; skipped in Droid output.`)
        continue
      }
      out[server.name] = {
        type: 'stdio',
        command: server.command,
        args: server.args ?? [],
        ...(server.env ? { env: server.env } : {}),
        ...shared
      }
      continue
    }

    if (!server.url) {
      warnings.push(`Server "${server.name}" has no url; skipped in Droid output.`)
      continue
    }
    out[server.name] = {
      type: server.transport,
      url: server.url,
      ...(server.headers ? { headers: server.headers } : {}),
      ...(server.oauth ? { oauth: server.oauth } : {}),
      ...shared
    }
  }

  return { mcpServers: out, warnings }
}

