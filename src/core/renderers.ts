/**
 * Render the project-scoped `.mcp.json` read by Claude Code and Copilot CLI.
 *
 * @param servers - Resolved MCP servers
 * @param options.tools - Emit the Copilot CLI `tools` allowlist (defaults to `['*']`)
 */
export function renderProjectMcpJson(
  servers: ResolvedMcpServer[],
  options?: { tools?: boolean; label?: string },
): { mcpServers: Record<string, unknown>; warnings: string[] } {
  const warnings: string[] = []
  const out: Record<string, unknown> = {}
  const label = options?.label ?? 'project .mcp.json'

  for (const server of servers) {
    if (server.transport === 'stdio') {
      if (!server.command) {
        warnings.push(`Server "${server.name}" has no command; skipped in ${label} output.`)
        continue
      }
      out[server.name] = {
        type: 'stdio',
        command: server.command,
        args: server.args ?? [],
        ...(server.cwd ? { cwd: server.cwd } : {}),
        ...(server.env ? { env: server.env } : {}),
        ...(options?.tools ? { tools: server.tools ?? ['*'] } : {})
      }
      continue
    }

    if (!server.url) {
      warnings.push(`Server "${server.name}" has no url; skipped in ${label} output.`)
      continue
    }
    out[server.name] = {
      type: server.transport,
      url: server.url,
      ...(server.headers ? { headers: server.headers } : {}),
      ...(server.headersHelper ? { headersHelper: server.headersHelper } : {}),
      ...(server.oauth ? { oauth: server.oauth } : {}),
      ...(options?.tools ? { tools: server.tools ?? ['*'] } : {})
    }
  }

  return { mcpServers: out, warnings }
}

